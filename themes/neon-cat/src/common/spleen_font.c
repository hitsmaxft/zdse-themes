static void draw8(const uint8_t rows[16],int x,int y,uint16_t color){
  for(int yy=0;yy<16;yy++)for(int xx=0;xx<8;xx++)if(rows[yy]&(1u<<(7-xx)))dtr_pixel565(x+xx,y+yy,color);
}
static void draw6_2x(const uint8_t rows[12],int x,int y,uint16_t color){
  for(int yy=0;yy<12;yy++)for(int xx=0;xx<6;xx++)if(rows[yy]&(1u<<(5-xx)))
    for(int dy=0;dy<2;dy++)for(int dx=0;dx<2;dx++)dtr_pixel565(x+xx*2+dx,y+yy*2+dy,color);
}

static const uint8_t *ui_rows(char code){
  for(unsigned int i=0;i<sizeof(ui_glyphs)/sizeof(ui_glyphs[0]);i++)if(ui_glyphs[i].code==code)return ui_glyphs[i].rows;
  return 0;
}

void zdse_spleen_ui(const char *text,int x,int y,int scale,int centered,int r,int g,int b){
  int count=0;while(text[count])count++;int width=count?count*5*scale:0;
  int pen=centered?x-width/2:x;uint16_t color=dtr_rgb(r,g,b);
  for(int i=0;text[i];i++,pen+=5*scale){
    const uint8_t *rows=ui_rows(text[i]);if(!rows)continue;
    for(int yy=0;yy<8;yy++)for(int xx=0;xx<5;xx++)if(rows[yy]&(1u<<(4-xx)))
      for(int dy=0;dy<scale;dy++)for(int dx=0;dx<scale;dx++)dtr_pixel565(pen+xx*scale+dx,y+yy*scale+dy,color);
  }
}

void zdse_spleen_wpm(int center_x,int y){
  uint16_t color=dtr_rgb(226,231,247);int x=center_x-12;
  for(int i=0;i<3;i++,x+=8)draw8(label_rows[i],x,y,color);
}

void zdse_spleen_number(int value,int center_x,int y){
  if(value<0)value=0;if(value>999)value=999;
  int digits=value>=100?3:value>=10?2:1,divisor=digits==3?100:digits==2?10:1;
  int x=center_x-digits*6;uint16_t color=dtr_rgb(125,239,255);
  while(divisor){draw6_2x(digit_rows[value/divisor%10],x,y,color);x+=12;divisor/=10;}
}
